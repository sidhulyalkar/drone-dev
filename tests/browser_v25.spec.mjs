import {test,expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';

test('an observation links to one requirement with a portable definition snapshot and becomes stale on variant change',async({page})=>{
 await page.goto('http://127.0.0.1:8080',{waitUntil:'domcontentloaded'});
 await page.locator('#af-workspace-engineering').click();
 await page.locator('#v22-inspection > summary').click();
 await page.locator('#v22-add > summary').click();
 await page.locator('#v22-part').selectOption('x500-esc20');
 await page.locator('#v22-kind').selectOption('connector_observation');
 await page.locator('#v22-label').fill('ESC fixture observed with MR30 family');
 await page.locator('#v22-revision').fill('SYNTHETIC-MARK-NOT-MANUFACTURER');
 await page.locator('#v22-observer').fill('Test Inspector A');
 await page.locator('#v22-date').fill('2026-10-11');
 await page.locator('#v22-connector-family').fill('MR30 claimed family');
 await page.locator('#v22-gender').fill('Key shape visually guessed; mating not tested');
 await page.locator('#v22-connector-method').fill('Synthetic photo comparison only');
 await page.locator('#v22-notes').fill('Only a fabricated browser fixture receipt; this does not prove mating or wiring.');
 await page.locator('#v22-form button[type=submit]').click();
 await expect(page.locator('#v22-events')).toContainText('evt-0001');
 await page.locator('#v23-checklist > summary').click();
 await expect(page.locator('#v23-checklist')).toContainText('0 of 18 checks');
 const motor=page.locator('#v23-checklist details').first();
 await motor.locator('summary').click();
 await motor.getByRole('button',{name:'Select this check'}).first().click();
 await expect(page.locator('#v23-checklist select').first()).toHaveValue('motor-esc');
 await expect(page.locator('#v23-checklist select').nth(1)).toHaveValue('0');
 await expect(page.locator('#v23-checklist select').nth(2)).toHaveValue('evt-0001');
 await page.locator('#v23-checklist textarea').fill('A visual MR30 observation informs connector keying, not verified polarity or fit.');
 await page.locator('#v23-checklist form button[type=submit]').click();
 await expect(page.locator('#v23-checklist')).toContainText('1 of 18 checks');
 await expect(page.locator('#v23-checklist')).toContainText('SELF_REPORTED_EVIDENCE_LINKED');
 const downloadPromise=page.waitForEvent('download');
 await page.getByRole('button',{name:'Export link research JSON'}).click();
 const exported=await downloadPromise;
 const data=JSON.parse(await readFile(await exported.path(),'utf8'));
 expect(data.links).toHaveLength(1);
 expect(data.links[0].requirementSnapshot).toMatch(/MR30/);
 expect(data.links[0].edgeSignature).toContain('x500-esc20');
 expect(data.powerApproved).toBe(false);
 await page.locator('#v06-kit-variant').selectOption('six_x');
 await expect(page.locator('#v23-checklist')).toContainText('0 of 18 checks');
 await page.locator('#v23-checklist details').first().locator('summary').click();
 await expect(page.locator('#v23-checklist')).toContainText('STALE_OR_INVALID_EVIDENCE');
});
test('without an existing inspection observation, a check is missing evidence and cannot be linked',async({page})=>{
 await page.goto('http://127.0.0.1:8080',{waitUntil:'domcontentloaded'});
 await page.locator('#af-workspace-engineering').click();
 await page.locator('#v22-inspection > summary').click();
 await page.locator('#v23-checklist > summary').click();
 await expect(page.locator('#v23-checklist')).toContainText('18 remain unqualified');
 await expect(page.locator('#v23-checklist form button[type=submit]')).toBeDisabled();
 await page.locator('#v23-checklist details').first().locator('summary').click();
 await expect(page.locator('#v23-checklist')).toContainText('EVIDENCE MISSING');
});
